export type IconName = keyof typeof REGISTRY | string

interface IconProps {
  name: IconName
  size?: number
  strokeWidth?: number
  className?: string
}

export function Icon({ name, size = 18, strokeWidth = 1.7, className }: IconProps) {
  const Cmp = REGISTRY[name] ?? MoreHorizontal
  return <Cmp size={size} strokeWidth={strokeWidth} className={className} aria-hidden="true" />
}

export function iconExists(name: string): boolean {
  return name in REGISTRY
}
